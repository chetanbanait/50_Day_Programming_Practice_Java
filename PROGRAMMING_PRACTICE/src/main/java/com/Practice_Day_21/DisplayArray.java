package com.Practice_Day_21;

public class DisplayArray {
    public static void main(String[] args) {

        int[] arr = {5, 10, 15, 20, 25};

        System.out.println("Array Elements:");

        for (int i = 0; i < arr.length; i++) {
            System.out.print(arr[i] + " ");
        }
    }
}